#!/usr/bin/env node
/**
 * Writes src/tenant-models.generated.ts: every model in prisma/schema.prisma that has a
 * `tenantId` column, whether that column is nullable, and the name of the relation field
 * that points at Tenant through it (if any).
 *
 * The API's tenant filter extension reads this list, so tenant-owned models are taken from
 * the schema rather than maintained by hand. src/__tests__/tenant-models.test.ts fails when
 * the committed file and the schema disagree; run `pnpm --filter @intelliflow/db
 * generate:tenant-models` after a schema change.
 *
 *   node packages/db/scripts/generate-tenant-models.mjs [--check]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SCHEMA_PATH = path.join(pkgRoot, 'prisma', 'schema.prisma');
export const OUTPUT_PATH = path.join(pkgRoot, 'src', 'tenant-models.generated.ts');

/** Strips `//` comments so commented-out fields are not read as columns. */
function stripComments(text) {
  return text.replace(/\/\/[^\n]*/g, '');
}

/**
 * @param {string} schemaText the contents of schema.prisma
 * @returns {{ model: string, nullable: boolean, defaulted: boolean, relation: string | null }[]} sorted by model
 */
export function parseTenantModels(schemaText) {
  const out = [];
  const modelRe = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
  for (const match of stripComments(schemaText).matchAll(modelRe)) {
    const [, model, body] = match;
    const column = body
      .split('\n')
      .map((line) => line.trim().split(/\s+/))
      .find(([name, type]) => name === 'tenantId' && (type === 'String' || type === 'String?'));
    const defaulted = Boolean(column?.slice(2).some((token) => token.startsWith('@default(')));
    if (!column) continue;
    let relation = null;
    for (const line of body.split('\n')) {
      const field = line.match(/^\s*(\w+)\s+Tenant\??\s+@relation\(([^)]*)\)/);
      if (field && /fields:\s*\[[^\]]*\btenantId\b[^\]]*\]/.test(field[2])) {
        relation = field[1];
        break;
      }
    }
    out.push({ model, nullable: column[1] === 'String?', defaulted, relation });
  }
  return out.sort((a, b) => a.model.localeCompare(b.model));
}

/** The TypeScript source of src/tenant-models.generated.ts for `models`. */
export function renderTenantModels(models) {
  const rows = models
    .map(
      (m) =>
        `  ${m.model}: { nullable: ${m.nullable}, defaulted: ${m.defaulted}, relation: ${m.relation ? `'${m.relation}'` : 'null'} },`
    )
    .join('\n');
  return `// GENERATED by packages/db/scripts/generate-tenant-models.mjs from prisma/schema.prisma.
// Do not edit by hand: run \`pnpm --filter @intelliflow/db generate:tenant-models\`.

/** How a tenant-owned model stores its tenant. */
export interface TenantModelInfo {
  /** \`tenantId\` is optional: rows with no tenant are shared by every tenant. */
  readonly nullable: boolean;
  /** \`tenantId\` has a column default (a sentinel such as 'global'): the rows are platform-wide. */
  readonly defaulted: boolean;
  /** The relation field that points at Tenant through \`tenantId\`, if the model has one. */
  readonly relation: string | null;
}

/** Every model with a \`tenantId\` column, keyed by Prisma model name. */
export const TENANT_MODELS: Readonly<Record<string, TenantModelInfo>> = {
${rows}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = renderTenantModels(parseTenantModels(fs.readFileSync(SCHEMA_PATH, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (current.replaceAll('\r\n', '\n') !== rendered) {
      console.error('tenant-models: src/tenant-models.generated.ts is out of date; regenerate it.');
      process.exit(1);
    }
    console.log('tenant-models: up to date');
  } else {
    fs.writeFileSync(OUTPUT_PATH, rendered);
    console.log(`tenant-models: wrote ${path.relative(pkgRoot, OUTPUT_PATH)}`);
  }
}
