/**
 * Traces a rounded rectangle on a 2D canvas path, the shape `roundRect` draws,
 * from arcs every browser supports (`roundRect` arrived in Safari 16). The
 * caller begins the path and fills or strokes it.
 */
export function roundedRect(
  g: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
): void {
  const radius = Math.max(0, Math.min(r, w / 2, h / 2));
  g.moveTo(x + radius, y);
  g.arcTo(x + w, y, x + w, y + h, radius);
  g.arcTo(x + w, y + h, x, y + h, radius);
  g.arcTo(x, y + h, x, y, radius);
  g.arcTo(x, y, x + w, y, radius);
  g.closePath();
}
