'use client';

/**
 * Download page for a copy of one's personal data (PG-203 DSAR; spec Addendum A and
 * sign-off 2).
 *
 * The emailed link's fragment is read once and stripped. Each "Get my data" press is one
 * of the limited downloads. The data is shown as a plain summary (React text nodes only,
 * never injected HTML) and can be saved as a JSON file; it stays in memory and is never
 * written to browser storage.
 */
import { useEffect, useRef, useState } from 'react';
import { Button } from '@intelliflow/ui';
import type { DsarExportDto } from '@intelliflow/validators/dsar';
import { trpc } from '@/lib/trpc';
import {
  DsarNotice,
  DsarPage,
  errorCode,
  takeDsarFragment,
  type DsarLink,
} from '../../dsar-shared';

const SECTION_LABELS: Record<string, string> = {
  leads: 'Enquiry records',
  leadScores: 'Scores generated by AI (derived data)',
  leadActivities: 'Contact history on enquiries',
  contacts: 'Contact records',
  contactActivities: 'Contact history',
  bookings: 'Appointments you booked',
  emailRecords: 'Emails (dates only)',
  tickets: 'Support tickets',
  chats: 'Chats (dates only)',
  feedback: 'Your feedback',
  dataRequests: 'Your data requests',
  leadInsights: 'Insights generated by AI on enquiries (derived data)',
  contactInsights: 'Insights generated by AI on contact records (derived data)',
  aiInsights: 'Other insights generated by AI (derived data)',
};

type WithheldCategory = DsarExportDto['withheld'][number]['category'];

const WITHHELD_LABELS: Record<WithheldCategory, string> = {
  NOTES: 'Staff notes',
  ACTIVITY_TEXT: 'Text of contact history entries',
  TICKET_SUBJECTS: 'Support ticket subjects',
  MESSAGE_BODIES: 'Email and chat messages',
  DOCUMENTS: 'Documents',
  EXCESS_ROWS: 'Records beyond the automatic file limit',
};

const FILE_NAME = 'my-personal-data.json';

/** Save the export as a file from memory (no storage, nothing sent anywhere). */
export function saveExport(data: DsarExportDto, doc: Document = document): void {
  const url = URL.createObjectURL(
    new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' })
  );
  const anchor = doc.createElement('a');
  anchor.href = url;
  anchor.download = FILE_NAME;
  anchor.click();
  URL.revokeObjectURL(url);
}

function Summary({ data }: Readonly<{ data: DsarExportDto }>) {
  const info = data.processingInformation;
  const sections = Object.entries(data.data);
  return (
    <div className="mt-6 space-y-8">
      <section aria-labelledby="export-data">
        <h2 id="export-data" className="text-lg font-semibold text-foreground">
          What the file contains
        </h2>
        <ul className="mt-2 list-disc space-y-1 pl-5 text-foreground">
          {sections.map(([key, rows]) => (
            <li key={key}>{`${SECTION_LABELS[key] ?? key}: ${rows.length}`}</li>
          ))}
        </ul>
      </section>

      {data.withheld.length > 0 && (
        <section aria-labelledby="export-withheld">
          <h2 id="export-withheld" className="text-lg font-semibold text-foreground">
            Not in this file yet
          </h2>
          <p className="mt-1 text-sm text-muted-foreground">{data.withheld[0]!.note}</p>
          <ul className="mt-2 list-disc space-y-1 pl-5 text-foreground">
            {data.withheld.map((item) => (
              <li key={item.category}>
                {`${WITHHELD_LABELS[item.category] ?? item.category}: ${item.count}`}
              </li>
            ))}
          </ul>
        </section>
      )}

      <section aria-labelledby="export-info" className="space-y-3 text-sm text-foreground">
        <h2 id="export-info" className="text-lg font-semibold text-foreground">
          How your data is used
        </h2>
        <p>{`Controller: ${info.controller.name}`}</p>
        <InfoList title="Purposes" items={info.purposes} />
        <InfoList title="Categories of data" items={info.categories} />
        <InfoList title="Who receives it" items={info.recipients} />
        <p>{`Retention: ${info.retention}`}</p>
        <p>{`Source: ${info.source}`}</p>
        <InfoList title="Your rights" items={info.rights} />
        <p>{info.automatedDecisions}</p>
        <p>{info.complaint}</p>
      </section>
    </div>
  );
}

function InfoList({ title, items }: Readonly<{ title: string; items: string[] }>) {
  return (
    <div>
      <h3 className="font-medium">{title}</h3>
      <ul className="list-disc pl-5">
        {items.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ul>
    </div>
  );
}

/** What to tell the person when a download fails. */
export function downloadErrorMessage(error: unknown): string {
  const code = errorCode(error);
  if (code === 'TOO_MANY_REQUESTS' && error instanceof Error && error.message) {
    return error.message;
  }
  return 'This link is invalid or has expired. Contact the firm for a new one.';
}

export default function DsarExportContent() {
  const download = trpc.privacy.downloadExport.useMutation();
  // Read once into the ref (StrictMode's second effect run must not re-read a stripped URL).
  const taken = useRef<DsarLink | null | undefined>(undefined);
  const [link, setLink] = useState<DsarLink | null | undefined>(undefined);
  const [data, setData] = useState<DsarExportDto | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (taken.current === undefined) taken.current = takeDsarFragment();
    setLink(taken.current);
  }, []);

  if (link === undefined) {
    return (
      <DsarNotice title="Your personal data">
        <output>Please wait</output>
      </DsarNotice>
    );
  }
  if (!link) {
    return (
      <DsarNotice title="This link is incomplete">
        <p>Open the link from the email again, in full.</p>
      </DsarNotice>
    );
  }

  const fetchData = async (current: DsarLink) => {
    setError(null);
    try {
      setData(await download.mutateAsync(current));
    } catch (failure) {
      setError(downloadErrorMessage(failure));
    }
  };

  return (
    <DsarPage>
      <h1 className="text-2xl font-semibold text-foreground">Your personal data</h1>
      {data ? (
        <>
          <p className="mt-3 text-foreground">
            {`From ${data.processingInformation.controller.name}, prepared ${new Date(
              data.generatedAt
            ).toLocaleString('en-GB')}.`}
          </p>
          <Button type="button" className="mt-4" onClick={() => saveExport(data)}>
            Save as a file
          </Button>
          <Summary data={data} />
        </>
      ) : (
        <>
          <p className="mt-3 text-muted-foreground">
            The link can be used a limited number of times. Save the file once you have it.
          </p>
          <Button
            type="button"
            className="mt-4"
            disabled={download.isPending}
            onClick={() => {
              fetchData(link).catch(() => setError(downloadErrorMessage(null)));
            }}
          >
            {download.isPending ? 'Preparing…' : 'Get my data'}
          </Button>
        </>
      )}
      {error && (
        <p role="alert" className="mt-4 text-sm text-red-700 dark:text-red-300">
          {error}
        </p>
      )}
    </DsarPage>
  );
}
